#!/usr/bin/env python3
"""Bake the approved joined UI outline into palette-role tiles, without text
or portraits. Byte RLE keeps the ROM small and avoids a per-pixel distance
transform on the ARM7 when the speaker changes. No image dependency required.
"""
from pathlib import Path

WIDTH, HEIGHT = 256, 96


def frame(mode, letters):
    portrait, right = mode != 0, mode == 2
    width = letters * 8 + 16
    tab_x = (168 - width if right else 56) if portrait else 0
    regions = [(0, 56, 224, 40)]
    if portrait:
        regions.append((168 if right else 0, 0, 56, 60))
    if letters:
        regions.append((tab_x - (4 if portrait and not right else 0), 40, width + (4 if portrait else 0), 20))
    field = bytearray(WIDTH * HEIGHT)
    for x, y, w, h in regions:
        for yy in range(h):
            for xx in range(w):
                if min(xx + yy, w - 1 - xx + yy, xx + h - 1 - yy, w + h - 2 - xx - yy) >= 3 and y + yy < HEIGHT:
                    field[(y + yy) * WIDTH + x + xx] = 4

    def at(x, y):
        return field[y * WIDTH + x] if 0 <= x < WIDTH and 0 <= y < HEIGHT else 0

    for y in range(HEIGHT):
        for x in range(WIDTH):
            if at(x, y):
                field[y * WIDTH + x] = min(at(x, y), at(x - 1, y) + 1, at(x, y - 1) + 1)
    for y in reversed(range(HEIGHT)):
        for x in reversed(range(WIDTH)):
            if at(x, y):
                field[y * WIDTH + x] = min(at(x, y), at(x + 1, y) + 1, at(x, y + 1) + 1)
    if letters:
        for y in range(43, 56):
            for x in range(tab_x + 3, tab_x + width - 3):
                field[y * WIDTH + x] = 5
    tiles = bytearray(384 * 32)
    for y in range(HEIGHT):
        for x in range(WIDTH):
            part = x // 64
            tile = part * 64 + y // 8 * 8 + x % 64 // 8 if y < 64 else 256 + part * 32 + (y - 64) // 8 * 8 + x % 64 // 8
            tiles[tile * 32 + y % 8 * 4 + x % 8 // 2] |= field[y * WIDTH + x] << ((x & 1) * 4)
    return tiles


def generate():
    data, offsets = bytearray(), []
    for mode in range(3):
        for letters in range(20):
            offsets.append(len(data))
            tiles = frame(mode, letters)
            start = 0
            while start < len(tiles):
                end = start + 1
                while end < len(tiles) and tiles[end] == tiles[start]:
                    end += 1
                count = end - start
                data.extend([count & 255, count >> 8, tiles[start]])
                start = end
    lines = ["/* Generated by tools/generate_portrait_tab_frames.py. Palette roles only. */", "#pragma once", "#include <stdint.h>",
             "static const uint32_t portrait_tab_frame_offsets[60] = { " + ", ".join(map(str, offsets)) + " };",
             "static const uint8_t portrait_tab_frame_rle[] = {"]
    lines += ["    " + ", ".join(map(str, data[i:i + 24])) + "," for i in range(0, len(data), 24)]
    lines.append("};\n")
    return "\n".join(lines)


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "engine/include/gbs/portrait_tab_frame_data.h"
    target.write_text(generate())
