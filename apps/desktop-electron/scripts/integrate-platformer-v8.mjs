import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {promotePlatformerV8,PLATFORMER_V8_BG} from './promote-platformer-v8.mjs';
const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const candidate = '/Users/example/Pictures/Assets Exemplo/plataforma/plataforma-gba-v8-candidate';
const evidence = path.join(candidate,'integracao');
await mkdir(evidence,{recursive:true});
const project = path.join(app,'default-assets/templates/exemplo-gba/exemplo-gba.gba-project');
const before = await readFile(project,'utf8');
const backup = path.join(evidence,'before.gba-project');
if (!existsSync(backup)) await writeFile(backup,before,{flag:'wx'});
const source = path.join(candidate,'bg-1288x160-review.png');
const prepared = path.join(evidence,PLATFORMER_V8_BG);
execFileSync('/opt/homebrew/bin/ffmpeg',['-v','error','-y','-i',source,'-pix_fmt','rgba','-frames:v','1',prepared]);
const hash = createHash('sha256').update(await readFile(prepared)).digest('hex');
const next = promotePlatformerV8(JSON.parse(before));
next.assets.find(a=>a.name===PLATFORMER_V8_BG).metadata.sourceSha256=hash;
await copyFile(prepared,path.join(path.dirname(project),'Assets/backgrounds',PLATFORMER_V8_BG));
await writeFile(project,JSON.stringify(next,null,2)+'\n');
await writeFile(path.join(evidence,'manifest.json'),JSON.stringify({source,project,hash,status:'source-approved-integrated-runtime-attention',actors:'unchanged pixels and animations'},null,2)+'\n');
console.log('Integrated v8 source; actor art unchanged; runtime remains attention.');
