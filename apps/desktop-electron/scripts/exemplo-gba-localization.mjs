export function localizeExemploGBAProject(data) {
  data.localization = {
    sourceLocale: "en",
    defaultLocale: "pt-BR",
    enabledLocales: ["pt-BR", "en", "es"],
    offlineTranslation: {
      provider: "bergamot",
      bundledPairs: ["enpt", "pten"],
      reviewRequired: true
    }
  };
  const dialogues = Array.isArray(data.dialogues) ? data.dialogues : [];
  for (const dialogue of dialogues) {
    const existingTranslations = dialogue.translations && typeof dialogue.translations === "object"
      ? dialogue.translations
      : {};
    const fallback = translations[dialogue.key] ?? [
      existingTranslations["pt-BR"],
      existingTranslations.es,
      dialogue.choiceTranslations?.["pt-BR"],
      dialogue.choiceTranslations?.es
    ];
    const ptBR = typeof existingTranslations["pt-BR"] === "string"
      ? existingTranslations["pt-BR"]
      : fallback[0];
    const es = typeof existingTranslations.es === "string"
      ? existingTranslations.es
      : fallback[1];
    const ptChoices = Array.isArray(dialogue.choiceTranslations?.["pt-BR"])
      ? dialogue.choiceTranslations["pt-BR"]
      : fallback[2] ?? [];
    const esChoices = Array.isArray(dialogue.choiceTranslations?.es)
      ? dialogue.choiceTranslations.es
      : fallback[3] ?? [];
    if (typeof ptBR !== "string" || typeof es !== "string") {
      throw new Error(`Traducao ausente para ${dialogue.key}`);
    }
    dialogue.translations = {
      ...(dialogue.text ? { "pt-BR": ptBR, es } : {})
    };
    dialogue.choiceTranslations = {
      ...(Array.isArray(dialogue.choices) && dialogue.choices.length > 0
        ? { "pt-BR": ptChoices, es: esChoices }
        : {})
    };
    dialogue.translationStatus = { "pt-BR": "approved", es: "approved" };
    delete dialogue.translation;
    delete dialogue.translationLanguageCode;
  }
  return data;
}
