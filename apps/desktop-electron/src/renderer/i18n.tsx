export function getStudioTranslation(
  locale: StudioLocale,
  key: StudioTranslationKey,
  values: TranslationValues = {}
): string {
  const message = translations[locale][key] ?? translations["en-US"][key] ?? translations[defaultLocale][key] ?? key;
  return formatTranslation(message, values);
}

type StudioI18nContextValue = {
  locale: StudioLocale;
  localeOption: StudioLocaleOption;
  setLocale(locale: StudioLocale): void;
  t(key: StudioTranslationKey, values?: TranslationValues): string;
};

const StudioI18nContext = createContext<StudioI18nContextValue | null>(null);

export function isSupportedLocale(locale: string | null | undefined): locale is StudioLocale {
  return localeOptions.some((option) => option.locale === locale);
}

export function resolveLocale(locale: string | null | undefined): StudioLocale {
  if (locale === "es-419") return "es-ES";
  return isSupportedLocale(locale) ? locale : defaultLocale;
}

export function readStoredLocale(): StudioLocale {
  try {
    return resolveLocale(window.localStorage.getItem(storageKey));
  } catch {
    return defaultLocale;
  }
}

export function writeStoredLocale(locale: StudioLocale): void {
  try {
    window.localStorage.setItem(storageKey, locale);
  } catch {
    // Ignore storage failures; the in-memory locale still updates.
  }
}

function formatTranslation(message: string, values: TranslationValues = {}): string {
  return Object.entries(values).reduce(
    (formatted, [key, value]) => formatted.replaceAll(`{${key}}`, String(value)),
    message
  );
}

export function StudioI18nProvider({ children }: { children: React.ReactNode }): React.ReactElement {
  const [locale, setLocaleState] = useState<StudioLocale>(() => readStoredLocale());

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar-SA" ? "rtl" : "ltr";
    document.documentElement.dataset.studioLocale = locale;
  }, [locale]);

  const value = useMemo<StudioI18nContextValue>(() => {
    const localeOption = localeOptions.find((option) => option.locale === locale) ?? localeOptions[0]!;

    return {
      locale,
      localeOption,
      setLocale(nextLocale) {
        writeStoredLocale(nextLocale);
        setLocaleState(nextLocale);
      },
      t: (key, values) => getStudioTranslation(locale, key, values)
    };
  }, [locale]);

  return (
    <StudioI18nContext.Provider value={value}>
      {children}
    </StudioI18nContext.Provider>
  );
}

export function useStudioI18n(): StudioI18nContextValue {
  const value = useContext(StudioI18nContext);
  if (!value) {
    throw new Error("useStudioI18n must be used inside StudioI18nProvider.");
  }
  return value;
}

type StudioLanguageSwitcherProps = {
  className?: string;
};

export function StudioLanguageSwitcher({ className }: StudioLanguageSwitcherProps): React.ReactElement {
  const { locale, localeOption, setLocale, t } = useStudioI18n();

  return (
    <label className={["studio-language-switcher", className].filter(Boolean).join(" ")} title={t("language.title")}>
      <span aria-hidden="true" className="studio-language-flag">{localeOption.flagLabel}</span>
      <strong>{localeOption.shortLabel}</strong>
      <select
        aria-label={t("language.ariaLabel")}
        dir={locale === "ar-SA" ? "rtl" : "ltr"}
        onChange={(event) => setLocale(resolveLocale(event.currentTarget.value))}
        value={locale}
      >
        {localeOptions.map((option) => (
          <option key={option.locale} value={option.locale}>
            {option.label}
          </option>
        ))}
      </select>
    </label>
  );
}
